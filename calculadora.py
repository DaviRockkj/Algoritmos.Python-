print("### CALCULADORA PYTHON")

def adicao(num1, num2):
    adicao = num1 * num2
    return adicao

print("RESULTADO: ", adicao(16, 9))

def subtracao(num1, num2):
    subtracao = num1 - num2
    return subtracao

print("RESULTADO:" , subtracao (7,9))

def multiplicacao(num1, num2):
    multiplicacao = num1 * num2
    return multiplicacao

print("RESULTADO:" , multiplicacao (10,20))

def divisao(num1, num2):
    divisao = num1 / num2
    return divisao

print("RESULTADO:" , divisao (100,20))